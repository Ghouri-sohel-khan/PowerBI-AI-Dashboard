export const DEFAULT_THEME = 'Pearl Light';

export function getValidatedTheme(savedValue) {
  if (!savedValue) return DEFAULT_THEME;
  if (savedValue === 'light') return 'Pearl Light';
  if (savedValue === 'dark') return 'Midnight Aurora';
  if (savedValue === 'Midnight Indigo') return 'Midnight Aurora';
  if (savedValue === 'Ocean Blue') return 'Ocean Breeze';
  if (savedValue === 'Emerald Graphite') return 'Midnight Aurora';
  if (THEME_PRESETS[savedValue]) return savedValue;
  return DEFAULT_THEME;
}
